// generateGCEPD vendors the Linux base without invoking Kustomize. Identity
// fragments remain chart-owned; upstream owns the workloads and RBAC.
func generateGCEPD(outDir, version string) error {
	for _, file := range []string{"controller/cluster_setup.yaml", "controller/controller.yaml", "controller/v1_csidriver.yaml", "controller/rbac-taint-controller.yaml", "node_linux/node.yaml"} {
		body, err := download(fmt.Sprintf("https://raw.githubusercontent.com/kubernetes-sigs/gcp-compute-persistent-disk-csi-driver/%s/deploy/kubernetes/base/%s", version, file))
		if err != nil {
			return err
		}
		for _, raw := range splitYAMLDocuments(body) {
			var doc map[string]any
			if err := yaml.Unmarshal(raw, &doc); err != nil {
				return err
			}
			metadata := doc["metadata"].(map[string]any)
			name := metadata["name"].(string)
			kind := doc["kind"].(string)
			if strings.Contains(name, "-win") || strings.Contains(name, "snapshotter") || name == "csi-gce-pd-controller-deploy" {
				continue
			}
			// The node-deploy role also contains real node permissions. Keep
			// those, dropping only its obsolete PSP rule and renaming references.
			if name == "csi-gce-pd-node-deploy" {
				doc["rules"] = doc["rules"].([]any)[1:]
			}
			if kind == "ServiceAccount" || kind == "Deployment" || kind == "DaemonSet" || kind == "Role" || kind == "RoleBinding" {
				metadata["namespace"] = "NAMESPACE_TEMPLATE"
			}
			if subjects, ok := doc["subjects"].([]any); ok {
				for _, subject := range subjects {
					subject.(map[string]any)["namespace"] = "NAMESPACE_TEMPLATE"
				}
			}
			if kind == "Deployment" || kind == "DaemonSet" {
				pod := doc["spec"].(map[string]any)["template"].(map[string]any)["spec"].(map[string]any)
				controller := kind == "Deployment"
				if controller {
					delete(pod, "hostNetwork")
				} else {
					delete(pod, "affinity")
				}
				pod["volumes"] = withoutNamed(pod["volumes"], "cloud-sa-volume")
				containers := withoutNamed(pod["containers"], "csi-snapshotter")
				for _, item := range containers {
					container := item.(map[string]any)
					containerName := container["name"].(string)
					imageName := map[string]string{"gce-pd-driver": "driver", "taint-controller": "driver", "csi-provisioner": "provisioner", "csi-attacher": "attacher", "csi-resizer": "resizer", "csi-driver-registrar": "registrar"}[containerName]
					if imageName == "" {
						return fmt.Errorf("unknown GCE PD container %q", containerName)
					}
					container["image"] = fmt.Sprintf("{{ .Values.images.%s.repository }}:{{ .Values.images.%s.tag }}", imageName, imageName)
					container["env"] = withoutNamed(container["env"], "GOOGLE_APPLICATION_CREDENTIALS")
					container["volumeMounts"] = withoutNamed(container["volumeMounts"], "cloud-sa-volume")
					if containerName == "csi-attacher" {
						container["args"] = append(container["args"].([]any), "--max-grpc-log-length=10000", "--default-fstype=ext4")
					}
					if controller && containerName == "gce-pd-driver" {
						container["args"] = append(container["args"].([]any), "--cloud-config=/etc/gce/cloud.conf", "--fail-close-on-auth-error=true")
						container["env"] = "IDENTITY_ENV_TEMPLATE"
						container["volumeMounts"] = append(container["volumeMounts"].([]any), "IDENTITY_MOUNTS_TEMPLATE")
					}
				}
				pod["containers"] = containers
				if controller {
					pod["volumes"] = append(pod["volumes"].([]any), "IDENTITY_VOLUMES_TEMPLATE")
				}
			}
			var output bytes.Buffer
			encoder := yaml.NewEncoder(&output)
			encoder.SetIndent(2)
			if err := encoder.Encode(doc); err != nil {
				return err
			}
			if err := encoder.Close(); err != nil {
				return err
			}
			rendered := strings.NewReplacer(
				"NAMESPACE_TEMPLATE", "{{ .Release.Namespace }}",
				"csi-gce-pd-controller-sa", "platform-csi-gce-pd-controller",
				"csi-gce-pd-node-sa", "platform-csi-gce-pd-node",
				"csi-gce-pd-node-deploy", "csi-gce-pd-node-role",
				"env: IDENTITY_ENV_TEMPLATE", "env: {{ include \"csi-gce-pd.identityEnv\" . | nindent 12 }}",
				"- IDENTITY_MOUNTS_TEMPLATE", "{{ include \"csi-gce-pd.identityMounts\" . | nindent 12 }}",
				"- IDENTITY_VOLUMES_TEMPLATE", "{{ include \"csi-gce-pd.identityVolumes\" . | nindent 8 }}",
			).Replace(output.String())
			header := "# Podplane <https://podplane.dev>\n# Copyright The Podplane Authors\n# SPDX-License-Identifier: Apache-2.0\n# Generated by scripts/crds; do not edit.\n---\n"
			if err := os.WriteFile(filepath.Join(outDir, strings.ToLower(kind)+"-"+name+".yaml"), []byte(header+rendered), 0o644); err != nil {
				return err
			}
		}
	}
	return nil
}

// withoutNamed filters a Kubernetes list without changing its remaining entries.
func withoutNamed(value any, name string) []any {
	items, _ := value.([]any)
	kept := []any{}
	for _, item := range items {
		if item.(map[string]any)["name"] != name {
			kept = append(kept, item)
		}
	}
	return kept
}
